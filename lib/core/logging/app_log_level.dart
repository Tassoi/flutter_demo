/// 应用日志事件使用的项目自有严重级别。
///
/// 该枚举同时用于环境最低阈值和日志事件，避免 `package:logging` 的 `Level` 类型进入
/// 配置、Feature 或测试契约。具体 adapter 负责把这些值映射到第三方实现。
enum AppLogLevel {
  /// 开发诊断，生产环境通常会在阈值过滤阶段丢弃。
  debug,

  /// 正常运行状态和有价值的生命周期事件。
  info,

  /// 可恢复异常、降级或需要关注的边界情况。
  warning,

  /// 操作失败、未捕获异常或无法继续当前流程的错误。
  error,
}
